    pdf.set_font('helvetica', 'B', 20)
    pdf.set_text_color(15, 23, 42)
    pdf.cell(0, 10, "Executive Website & SEO Audit Report", ln=1, align='L')

    pdf.set_font('helvetica', '', 10)
    pdf.set_text_color(100, 116, 139)
    pdf.cell(0, 6, f"Target Domain: {domain} | Generated: {datetime.now().strftime('%B %d, %Y')}", ln=1, align='L')
    pdf.ln(4)

    # Score & Grade Banner Card
    pdf.set_fill_color(30, 41, 59)
    pdf.rect(10, pdf.get_y(), 190, 24, 'F')

