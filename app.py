def generate_leads_pdf(
    leads_df: pd.DataFrame,
    niche: str,
    city: str,
    agency_name: str = "ApexLeads Agency Partners",
    agency_website: str = "https://apexleads.ai"
) -> bytes:
    """Generates a batch lead intelligence portfolio PDF report."""
    pdf = ApexCleanPDF(agency_name=agency_name, agency_website=agency_website)
    pdf.set_auto_page_break(auto=True, margin=15)
    pdf.add_page()

    # Title & Metadata
    pdf.set_font('helvetica', 'B', 20)
    pdf.set_text_color(15, 23, 42)
    pdf.cell(0, 10, "B2B Outbound Lead & Audit Portfolio", ln=1, align='L')

    pdf.set_font('helvetica', '', 10)
    pdf.set_text_color(100, 116, 139)
    pdf.cell(0, 6, f"Target: {niche} in {city} | Extracted Accounts: {len(leads_df)} Businesses", ln=1, align='L')
    pdf.ln(6)

    # Table Header
    pdf.set_fill_color(30, 41, 59)
    pdf.set_text_color(255, 255, 255)
    pdf.set_font('helvetica', 'B', 8.5)
    pdf.cell(50, 8, " Business Name", 1, 0, 'L', True)
    pdf.cell(48, 8, " Website Domain", 1, 0, 'L', True)
    pdf.cell(38, 8, " Phone Number", 1, 0, 'L', True)
    pdf.cell(36, 8, " Identified Flaw", 1, 0, 'L', True)
    pdf.cell(18, 8, " Score", 1, 1, 'C', True)

    # Table Rows
    pdf.set_font('helvetica', '', 8)
    pdf.set_text_color(30, 41, 59)
    fill = False
    for _, row in leads_df.iterrows():
        pdf.set_fill_color(241, 245, 249) if fill else pdf.set_fill_color(255, 255, 255)
        c_name = str(row.get("Business Name", "Business"))[:24]
        w_url = str(row.get("Website", "N/A")).replace("https://", "").replace("http://", "").replace("www.", "")[:24]
        phone = str(row.get("Phone", "N/A"))[:18]
        flaw = str(row.get("Identified Flaw", "Speed Optimization"))[:20]
        score = f"{row.get('Performance Score', 80)}/100"

        c_name_safe = c_name.encode('latin-1', 'replace').decode('latin-1')
        w_url_safe = w_url.encode('latin-1', 'replace').decode('latin-1')
        phone_safe = phone.encode('latin-1', 'replace').decode('latin-1')
        flaw_safe = flaw.encode('latin-1', 'replace').decode('latin-1')

        pdf.cell(50, 7, f" {c_name_safe}", 1, 0, 'L', fill)
        pdf.cell(48, 7, f" {w_url_safe}", 1, 0, 'L', fill)
        pdf.cell(38, 7, f" {phone_safe}", 1, 0, 'L', fill)
        pdf.cell(36, 7, f" {flaw_safe}", 1, 0, 'L', fill)
        pdf.cell(18, 7, f" {score}", 1, 1, 'C', fill)
        fill = not fill

    return bytes(pdf.output())


