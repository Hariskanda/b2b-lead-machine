    pdf.set_font('helvetica', 'B', 20)
    pdf.set_text_color(15, 23, 42)
    pdf.cell(0, 10, "Comprehensive Website & SEO Audit Report", ln=1, align='L')

    pdf.set_font('helvetica', '', 10)
