class ApexCleanPDF(FPDF):
    def __init__(self, agency_name: str, agency_website: str):
        super().__init__()
        self.agency_name = agency_name
        self.agency_website = agency_website

    def header(self):
        self.set_font('helvetica', 'B', 9)
        self.set_text_color(37, 99, 235)
        self.cell(0, 6, f"{self.agency_name.upper()} • B2B EXECUTIVE DOSSIER", border=0, align='L')
        self.ln(6)
        self.set_draw_color(203, 213, 225)
        self.line(10, 16, 200, 16)
        self.ln(6)

    def footer(self):
        self.set_y(-15)
        self.set_font('helvetica', 'I', 8)
        self.set_text_color(148, 163, 184)
        self.cell(0, 10, f"Confidential Report • Generated by {self.agency_name} ({self.agency_website}) • Page {self.page_no()}", align='C')


def generate_audit_pdf(
    url: str,
    score: int,
    grade: str,
    pillars: Dict[str, int],
    issues: Dict[str, Any],
    agency_name: str = "ApexLeads Agency Partners",
    agency_website: str = "https://apexleads.ai"
) -> bytes:
    """Formats a clean executive website audit report and returns latin-1 encoded PDF bytes."""
    domain = url.replace("https://", "").replace("http://", "").split("/")[0]

    pdf = ApexCleanPDF(agency_name=agency_name, agency_website=agency_website)
    pdf.set_auto_page_break(auto=True, margin=15)
